/// 极简双语：键 → 文案。默认中文，系统非中文时用英文。
library;

import 'dart:ui';

enum AppLang { zh, en }

AppLang langFromLocale(Locale? locale) {
  final code = locale?.languageCode ?? 'zh';
  return code == 'zh' ? AppLang.zh : AppLang.en;
}

/// 全局当前语言（启动时由 main 设置；切换语言时更新）。
AppLang currentLang = AppLang.zh;

String t(String key) {
  final map = currentLang == AppLang.zh ? _zh : _en;
  return map[key] ?? _en[key] ?? key;
}

/// 带占位符的文案：`tf('search.results', {'n': '12'})` → `12 条结果`。
///
/// 只用最朴素的 `{name}` 替换 —— 双语表里没有嵌套/复数规则，引一个 i18n 框架
/// 反而更重。
String tf(String key, Map<String, Object?> args) {
  var out = t(key);
  for (final e in args.entries) {
    out = out.replaceAll('{${e.key}}', '${e.value}');
  }
  return out;
}

