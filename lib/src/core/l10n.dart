import 'dart:ui';

enum AppLang { zh, en }

AppLang langFromLocale(Locale? locale) {
  final code = locale?.languageCode ?? 'zh';
  return code == 'zh' ? AppLang.zh : AppLang.en;
}

/// 全局当前语言（启动时由 main 设置；切换语言时更新）。
AppLang currentLang = AppLang.zh;

String t(String key) {
  final map = currentLang == AppLang.zh ? _zh : _en;
  return map[key] ?? _en[key] ?? key;
}

